"""Evaluate an aphasia-friendly summary against source article metadata.

Both inputs are JSON files with ``title`` and ``abstract`` fields. The source
file is typically ``summary.orig.json`` and the generated summary is typically
``summary.json``.

Runnable as an individual module as well as as an API

Usage:
    uv run python -m readable_af.evaluation.evaluate COMPARISON.json [ --json ]
"""

import argparse
import sys
from pathlib import Path
from typing import Literal

from langchain_anthropic import ChatAnthropic
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_openai import ChatOpenAI
from pydantic import BaseModel, Field, SecretStr, ValidationError
from ..config import Config
from ..output.comparison import ComparisonModel

Provider = Literal["openai", "anthropic"]

OPENAI_MODEL = "gpt-5-mini-2025-08-07"
ANTHROPIC_MODEL = "claude-sonnet-4-5-20250929"
SYSTEM_PROMPT = (
    "You are an expert editor that receives original scientific abstracts "
    "and evaluates aphasia-friendly summaries of them generated by another LLM. "
    "You will provide numerical scores "
    "from 1-10 for each of the provided criteria in the output.\n"
    "Be strict: rating a weak summary too highly will negatively affect the reader."
    "Here is an example of an original scientific abstract and a high-quality aphasia-friendly version which should receive a 10/10 on Accuracy, Simplicity, Clarity, and Naturalness. "
    "Original: The left dorsomedial prefrontal cortex (dmPFC) is known to be associated with volition and motor function but is often overlooked in models of the neural bases of language. In this retrospective study, we reveal a robust statistical association between a rare language profile disproportionately affecting self-generated, but not externally cued, language production and damage to left dmPFC in a large (n = 307) neurosurgical database using both voxel-based and multivariate lesion-symptom mapping (VLSM, MLSM). This profile was not attributable to motivational or motor speech deficits. We further demonstrate that the probability of presenting with this profile is nearly 15 times higher following a resection in the dorsomedial prefrontal cortex than a resection elsewhere in the brain. Finally, we present a first person account of recovery from this language syndrome by a professionally trained linguist in the Supplementary Materials. These findings leverage a large dataset to add to the predominantly case-dominated literature demonstrating that damage specific to the dmPFC can cause a unique linguistic disturbance disproportionately affecting spontaneous speech, and provide a rare person-centered narrative of the experience of aphasia that is informative to scientists and clinicians alike. Overall, this work highlights the role of the left dmPFC, rarely included in dominant models of the neural bases of language, in the volitional control of fluent, self-generated speech. "
    "Aphasia-friendly summary: This study is about a special part of the brain called the dmPFC or pre-SMA.\n"
    "We looked at a big group of people who had brain surgery.\n"
    "Many people had trouble talking on their own after surgeries in this brain area.\n"
    "They had less trouble talking when it was clear what they were supposed to say.\n"
    "These people wanted to talk, and did not have trouble moving their mouths.\n"
    "This taught us that the dmPFC / pre-SMA is likely important for speaking on your own.\n"
)


class SummaryRating(BaseModel):
    accuracy: int = Field(
        ge=1,
        le=10,
        description="Does the summary introduce hallucinations or contradict the original? "
        "Are there any statements that misrepresent the original abstract? "
        "An issue of glossing over details does not count as an accuracy problem. " 
        "The only thing that counts against accuracy is the inclusion of a false statement in the summary.",
    )
    accuracy_reason: str = Field(
        description="An example of an inaccurate statement from the summary that caused the accuracy rating to be lower."
    )
    coverage: int = Field(
        ge=1,
        le=10,
        description="Are the main arguments included? Are there critical details missing? "
        "Elements can be elided from the summary if they are not necesary to comprehend the point of the paper. "
        "However, if something is important in the abstract, this value should be reduced even if the concept is complex. ",
    )
    simplicity: int = Field(
        ge=1,
        le=10,
        description="Is the word choice used simple enough for the reader? "
        "This text should be readable to an elementary school audience. "
        "Complicated words should reduce this score, even if they are more accurate.",
    )
    clarity: int = Field(
        ge=1,
        le=10,
        description="Would the meaning of each sentence be clear to people of all "
        "reading levels? ANY words or sentences that MIGHT not make sense to a reader who is "
        "not informed on the topic should greatly reduce this score. ",
    )
    naturalness: int = Field(
        ge=1,
        le=10,
        description="How natural does the language sound? "
        "If this does not sound like something a native english speaker would say, this score should be greatly reduced. "
        "If the grammatical structures are uncommon among native English speakers, e.g. it says 'good talking' instead of 'communicating well', it should not score above a 5."
        "It should score below a 5 if even a single word is used in a way that a native english speaker would think was unusual.",
    )
    appropriateness_of_icons: int = Field(
        ge=1,
        le=10,
        description="From the keywords that are provided, how appropriate are the icons that accompany each bullet point? "
        "If you believe an icon might be _more_ confusing than having no icon, that should reduce this score by 3-4 points for EACH confusing icon.",
    )


def load_summary_comparison(file_path: Path) -> ComparisonModel:
    """Load a summary as saved out by the comparison output generator"""
    try:
        return ComparisonModel.model_validate_json(
            file_path.read_text(encoding="utf-8")
        )
    except ValidationError as error:
        raise ValueError(f"Invalid article JSON in {file_path}: {error}") from error


def create_model(provider: Provider) -> BaseChatModel:
    config = Config.get()
    if provider == "anthropic":
        if not config.anthropic_api_key:
            raise RuntimeError(
                "ANTHROPIC_API_KEY is required for the Anthropic provider."
            )
        return ChatAnthropic(
            model_name=ANTHROPIC_MODEL,
            api_key=SecretStr(config.anthropic_api_key),
            timeout=None,
            stop=None,
        )
    return ChatOpenAI(
        model=OPENAI_MODEL,
        api_key=SecretStr(config.openai_api_key),
    )


def evaluate(
    inputs: ComparisonModel,
    provider: Provider = "openai",
) -> SummaryRating:
    """Rate a generated title and abstract against the source article metadata."""
    user_message = inputs.model_dump_json()

    model = create_model(provider)
    structured_model = model.with_structured_output(
        SummaryRating,
        method="json_schema",
    )
    result = structured_model.invoke(
        [SystemMessage(content=SYSTEM_PROMPT), HumanMessage(content=user_message)]
    )
    if not isinstance(result, SummaryRating):
        raise RuntimeError("Model did not return a valid summary rating.")
    return result


def format_report(rating: SummaryRating) -> str:
    lines = [
        "=" * 60,
        "  AphasiaFriendly Summary Evaluation",
        "=" * 60,
    ]
    for name in SummaryRating.model_fields:
        score: int = getattr(rating, name)
        lines.append(f"{name.capitalize():<12} {score:>2}/10")
    lines.append("=" * 60)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Rate an aphasia-friendly summary JSON against its source article JSON."
        )
    )
    parser.add_argument(
        "input",
        type=Path,
        metavar="COMPARISON.json",
        help="File containing information about orignal and summarized article. Output by the 'comparison' generator.",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print the rating as JSON instead of a report",
    )
    parser.add_argument(
        "--provider",
        choices=("openai", "anthropic"),
        default="openai",
        help="Model provider to use (default: openai)",
    )
    args = parser.parse_args(argv)

    if not args.input.is_file():
        parser.error(f"Comparison JSON file not found: {args.input}")

    try:
        input = load_summary_comparison(args.input)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    rating = evaluate(input, provider=args.provider)
    if args.json:
        print(rating.model_dump_json(indent=2))
    else:
        print(format_report(rating))
    return 0


if __name__ == "__main__":
    sys.exit(main())
