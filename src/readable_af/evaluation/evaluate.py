"""Evaluate an aphasia-friendly summary against source article metadata.

Both inputs are JSON files with ``title`` and ``abstract`` fields. The source
file is typically ``summary.orig.json`` and the generated summary is typically
``summary.json``.

Usage:
    uv run python evaluation/evaluate.py SOURCE.json SUMMARY.json
    uv run python evaluation/evaluate.py SOURCE.json SUMMARY.json --json
"""

import argparse
import sys
from pathlib import Path
from typing import Literal

from langchain_anthropic import ChatAnthropic
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_openai import ChatOpenAI
from pydantic import BaseModel, Field, SecretStr, ValidationError
from readable_af.config import Config

Provider = Literal["openai", "anthropic"]

OPENAI_MODEL = "gpt-5-mini-2025-08-07"
ANTHROPIC_MODEL = "claude-sonnet-4-5-20250929"
SYSTEM_PROMPT = (
    "You are an expert editor that evaluates aphasia-friendly summaries of "
    "scientific articles generated by another LLM. Provide four numerical "
    "scores from 1-10, one for each criterion. Be strict: rating a weak summary "
    "too highly could negatively affect the reader. Ignore any HTML tags.\n\n"
    "Accuracy: Does the summary introduce hallucinations, contradict the source, "
    "or misrepresent or oversimplify it?\n"
    "Coverage: Are the main arguments included? Are critical details missing?\n"
    "Simplicity: Is the word choice simple enough for the reader?\n"
    "Clarity: Would each sentence be clear to people of all reading levels? Any "
    "sentence that might not make sense to a reader unfamiliar with the topic "
    "should greatly reduce this score."
)


class ArticleText(BaseModel):
    title: str
    abstract: str


class SummaryRating(BaseModel):
    accuracy: int = Field(
        ge=1,
        le=10,
        description="Does the summary introduce hallucinations or contradict the "
        "original? Is there anything that appears to misrepresent or oversimplify?",
    )
    coverage: int = Field(
        ge=1,
        le=10,
        description="Are the main arguments included? Are there critical details "
        "missing?",
    )
    simplicity: int = Field(
        ge=1,
        le=10,
        description="Is the word choice used simple enough for the reader?",
    )
    clarity: int = Field(
        ge=1,
        le=10,
        description="Would the meaning of each sentence be clear to people of all "
        "reading levels? Any sentences that MIGHT not make sense to a reader who is "
        "not informed on the topic should greatly reduce this score.",
    )


def load_article(file_path: Path) -> ArticleText:
    """Load and validate an article or summary JSON file."""
    try:
        return ArticleText.model_validate_json(file_path.read_text(encoding="utf-8"))
    except ValidationError as error:
        raise ValueError(f"Invalid article JSON in {file_path}: {error}") from error


def create_model(provider: Provider) -> BaseChatModel:
    config = Config.get()
    if provider == "anthropic":
        if not config.anthropic_api_key:
            raise RuntimeError(
                "ANTHROPIC_API_KEY is required for the Anthropic provider."
            )
        return ChatAnthropic(
            model_name=ANTHROPIC_MODEL,
            api_key=SecretStr(config.anthropic_api_key),
            timeout=None,
            stop=None,
        )
    return ChatOpenAI(
        model=OPENAI_MODEL,
        api_key=SecretStr(config.openai_api_key),
    )


def evaluate(
    source: ArticleText,
    summary: ArticleText,
    provider: Provider = "openai",
) -> SummaryRating:
    """Rate a generated title and abstract against the source article metadata."""
    user_message = (
        f"SOURCE TITLE:\n{source.title}\n\n"
        f"SOURCE ABSTRACT:\n{source.abstract}\n\n"
        f"GENERATED TITLE:\n{summary.title}\n\n"
        f"GENERATED ABSTRACT:\n{summary.abstract}"
    )

    model = create_model(provider)
    structured_model = model.with_structured_output(
        SummaryRating,
        method="json_schema",
    )
    result = structured_model.invoke(
        [SystemMessage(content=SYSTEM_PROMPT), HumanMessage(content=user_message)]
    )
    if not isinstance(result, SummaryRating):
        raise RuntimeError("Model did not return a valid summary rating.")
    return result


def format_report(rating: SummaryRating) -> str:
    lines = [
        "=" * 60,
        "  AphasiaFriendly Summary Evaluation",
        "=" * 60,
    ]
    for name in ("accuracy", "coverage", "simplicity", "clarity"):
        score: int = getattr(rating, name)
        lines.append(f"{name.capitalize():<12} {score:>2}/10")
    lines.append("=" * 60)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Rate an aphasia-friendly summary JSON against its source article JSON."
        )
    )
    parser.add_argument(
        "source",
        type=Path,
        metavar="SOURCE.json",
        help="Source article JSON containing title and abstract",
    )
    parser.add_argument(
        "summary",
        type=Path,
        metavar="SUMMARY.json",
        help="Generated summary JSON containing title and abstract",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print the rating as JSON instead of a report",
    )
    parser.add_argument(
        "--provider",
        choices=("openai", "anthropic"),
        default="openai",
        help="Model provider to use (default: openai)",
    )
    args = parser.parse_args(argv)

    if not args.source.is_file():
        parser.error(f"Source JSON file not found: {args.source}")
    if not args.summary.is_file():
        parser.error(f"Summary JSON file not found: {args.summary}")

    try:
        source = load_article(args.source)
        summary = load_article(args.summary)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    rating = evaluate(source, summary, provider=args.provider)
    if args.json:
        print(rating.model_dump_json(indent=2))
    else:
        print(format_report(rating))
    return 0


if __name__ == "__main__":
    sys.exit(main())
